export function getUniversitiesForMajor(major: string): University[] {
  // If exact match exists, return it
  if (UNIVERSITIES_BY_MAJOR[major]) {
    return UNIVERSITIES_BY_MAJOR[major];
  }

  // Keyword matching
  const lower = major.toLowerCase();
  if (lower.includes('bio') || lower.includes('med') || lower.includes('life')) {
    return UNIVERSITIES_BY_MAJOR['Biomedical & Life Sciences'];
  }
  if (lower.includes('robot') || lower.includes('mechanic') || lower.includes('hardware') || lower.includes('engine')) {
    return UNIVERSITIES_BY_MAJOR['Robotics & Hardware Engineering'];
  }
  if (lower.includes('econ') || lower.includes('data') || lower.includes('quant') || lower.includes('stat')) {
    return UNIVERSITIES_BY_MAJOR['Data Science & Economics'];
  }
  if (lower.includes('biz') || lower.includes('bus') || lower.includes('fin') || lower.includes('trade')) {
    return UNIVERSITIES_BY_MAJOR['Business & Financial Tech'];
  }

  // Default to Computer Science
  return UNIVERSITIES_BY_MAJOR['Computer Science (AI/ML)'];
}
