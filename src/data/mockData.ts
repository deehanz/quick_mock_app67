// Helper to get curated universities based on major
export function getUniversitiesForMajor(major: string): University[] {
  const m = major.toLowerCase();

  if (m.includes('robot') || m.includes('hardware') || m.includes('mechatron') || m.includes('automation')) {
    return UNIVERSITIES_ROBOTICS;
  }
  if (m.includes('data') || m.includes('econ') || m.includes('quant') || m.includes('statistic') || m.includes('econometric')) {
    return UNIVERSITIES_DATA_ECON;
  }
  if (m.includes('bio') || m.includes('med') || m.includes('health') || m.includes('genom') || m.includes('life science')) {
    return UNIVERSITIES_COMP_BIO;
  }
  if (m.includes('business') || m.includes('fin') || m.includes('manage') || m.includes('commerce') || m.includes('bank')) {
    return UNIVERSITIES_BUSINESS;
  }
  if (m.includes('aero') || m.includes('space') || m.includes('mech') || m.includes('propul') || m.includes('flight')) {
    return UNIVERSITIES_AEROSPACE;
  }

  // Default to Computer Science & AI
  return UNIVERSITIES_CS_AI;
}

